CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE s1_worker NOLOGIN;
CREATE ROLE s1_bypass NOLOGIN BYPASSRLS;
CREATE SCHEMA houselens AUTHORIZATION s1_worker;
SET ROLE s1_worker;
CREATE TABLE houselens."Properties" (
 "Id" uuid PRIMARY KEY, "City" varchar(20) NOT NULL, "District" varchar(20) NOT NULL,
 "Address" varchar(200), "AreaPing" numeric(10,2) NOT NULL, "Floor" varchar(20), "AgeYears" integer,
 "HasParking" boolean NOT NULL, "CurrentTotalPrice" numeric(12,2) NOT NULL,
 "CurrentUnitPrice" numeric(12,2), "Status" integer NOT NULL, "Score" numeric(5,4), "IsNew" boolean NOT NULL,
 "FirstSeenAt" timestamptz NOT NULL, "LastSeenAt" timestamptz NOT NULL,
 "MissingCount" integer NOT NULL DEFAULT 0, "MergedIntoPropertyId" uuid);
CREATE TABLE houselens."Listings" (
 "Id" uuid PRIMARY KEY, "PropertyId" uuid NOT NULL REFERENCES houselens."Properties",
 "SourceSite" integer NOT NULL, "SourceListingKey" varchar(100) NOT NULL,
 "Title" varchar(200) NOT NULL, "Url" varchar(500) NOT NULL, "PostedDate" timestamptz,
 "LatestSourcePrice" numeric(12,2) NOT NULL, "IsActive" boolean NOT NULL, "ImageUrl" varchar(1000),
 UNIQUE ("SourceSite", "SourceListingKey"));
CREATE TABLE houselens."CrawlRuns" (
 "Id" uuid PRIMARY KEY, "StartedAt" timestamptz NOT NULL, "FinishedAt" timestamptz,
 "Status" integer NOT NULL, "NewCount" integer NOT NULL, "DelistedCount" integer NOT NULL, "BigDropCount" integer NOT NULL);
CREATE TABLE houselens."PriceHistoryEntries" (
 "Id" uuid PRIMARY KEY, "PropertyId" uuid NOT NULL REFERENCES houselens."Properties",
 "CrawlRunId" uuid NOT NULL REFERENCES houselens."CrawlRuns", "CapturedAt" timestamptz NOT NULL,
 "TotalPrice" numeric(12,2) NOT NULL, "UnitPrice" numeric(12,2), "SourceSite" integer NOT NULL,
 "ChangeFlag" integer NOT NULL, "ChangePercent" numeric(8,4), "IsBigDrop" boolean NOT NULL,
 UNIQUE ("PropertyId", "CrawlRunId", "SourceSite"));
CREATE TABLE houselens."DistrictConfigs" (
 "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "City" varchar(20) NOT NULL,
 "District" varchar(20) NOT NULL, "MaxTotalPrice" numeric(12,2) NOT NULL,
 "IsEnabled" boolean NOT NULL, "MaxAgeYears" integer NOT NULL, "ParkingCodes" text NOT NULL,
 UNIQUE ("City", "District"));
CREATE TABLE houselens."SourceRunResults" (
 "Id" uuid PRIMARY KEY, "CrawlRunId" uuid NOT NULL REFERENCES houselens."CrawlRuns",
 "SourceSite" integer NOT NULL, "Success" boolean NOT NULL, "FetchedCount" integer NOT NULL, "ErrorMessage" varchar(1000));
CREATE TABLE houselens."ViewerMembers" ("UserId" uuid PRIMARY KEY);
CREATE TABLE houselens."NotificationLogs" ("Id" uuid PRIMARY KEY, "ErrorMessage" text);
CREATE TABLE houselens."TrackingCriteria" ("Id" integer PRIMARY KEY, "Districts" text);
CREATE TABLE houselens."ScoringConfigs" ("Id" integer PRIMARY KEY);
CREATE TABLE houselens."PlatformFilterConfigs" ("Id" integer PRIMARY KEY);
GRANT USAGE ON SCHEMA houselens TO s1_bypass;
GRANT SELECT, INSERT, UPDATE, DELETE ON houselens."Properties" TO s1_bypass;
